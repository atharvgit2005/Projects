function slugify(value: string) {
  return value
    .toLowerCase()
    .trim()
    .replace(/\+/g, " plus ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)+/g, "");
}

function createYoutubeLinks(offset: number) {
  return [
    `https://www.youtube.com/watch?v=${youtubeIds[offset % youtubeIds.length]}`,
    `https://www.youtube.com/watch?v=${youtubeIds[(offset + 3) % youtubeIds.length]}`,
  ];
}

function imageSet(category: keyof typeof imagePools, offset: number) {
  const pool = imagePools[category];
  return [
    pool[offset % pool.length],
    pool[(offset + 1) % pool.length],
  ];
}

function deriveOriginalPrice(price: number, discountPercent: number) {
  if (!discountPercent) {
    return null;
  }

  return Math.round(price / (1 - discountPercent / 100));
}

function buildDescription(input: {
  title: string;
  condition: "new" | "second-hand";
  processor: string;
  display: string;
  battery: string;
  camera: string;
  useCase: string;
}) {
  const prefix =
    input.condition === "second-hand"
      ? `${input.title} is a carefully described second-hand device for buyers who want strong value without compromising core performance.`
      : `${input.title} is designed for customers who want a dependable mix of performance, display quality, battery life, and day-to-day usability.`;

  return `${prefix} It combines ${input.processor} performance, a ${input.display}, ${input.battery} endurance, and ${input.camera}. This listing is positioned for ${input.useCase}.`;
}

function createProduct(input: {
  title: string;
  brandSlug: string;
  categorySlug: keyof typeof imagePools;
  condition?: "new" | "second-hand";
  price: number;
  discountPercent: number;
  stock: number;
  featured?: boolean;
  latestRelease?: boolean;
  upcoming?: boolean;
  upcomingReleaseDate?: string | null;
  specs: SeedProduct["specs"];
  tags: string[];
  shortDescription: string;
  useCase: string;
  sku: string;
}) {
  const slug = slugify(input.title);
  const images = imageSet(input.categorySlug, input.sku.length);

  return {
    title: input.title,
    slug,
    brandSlug: input.brandSlug,
    categorySlug: input.categorySlug,
    description: buildDescription({
      title: input.title,
      condition: input.condition ?? "new",
      processor: input.specs.processor,
      display: input.specs.display,
      battery: input.specs.battery,
      camera: input.specs.camera,
      useCase: input.useCase,
    }),
    shortDescription: input.shortDescription,
    condition: input.condition ?? "new",
    price: input.price,
    originalPrice: deriveOriginalPrice(input.price, input.discountPercent),
    discountPercent: input.discountPercent,
    stock: input.stock,
    sku: input.sku,
    images,
    thumbnail: images[0],
    featured: Boolean(input.featured),
    latestRelease: Boolean(input.latestRelease),
    upcoming: Boolean(input.upcoming),
    upcomingReleaseDate: input.upcoming ? input.upcomingReleaseDate ?? null : null,
    youtubeReviewLinks: createYoutubeLinks(input.sku.length),
    specs: input.specs,
    tags: input.tags,
    isActive: true,
  } satisfies SeedProduct;
}

